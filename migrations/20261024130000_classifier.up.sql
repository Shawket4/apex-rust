-- ---------------------------------------------------------------------------
-- report_group: what a category means for the totals.
--   operating — running costs.
--   capital   — trucks, equipment, loan repayments: real money out, kept
--               apart from running costs.
--   excluded  — not spending at all. Money moving between the company's own
--               accounts, PetroApp top-ups (the fuel is counted from
--               PetroApp's own bills), refunded transfers, personal spending.
--               Shown in the ledger, never summed.
-- ---------------------------------------------------------------------------
ALTER TABLE banksms.categories
  ADD COLUMN report_group TEXT NOT NULL DEFAULT 'operating'
  CHECK (report_group IN ('operating', 'capital', 'excluded'));

