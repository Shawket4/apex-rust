-- ---------------------------------------------------------------------------
-- linked_loan_id: the public.loans row (entered in FalconGo) that this bank
-- payment is the money for. A reference only: apex-rust never modifies that
-- loan, never registers a second one for this payment, and the ledger shows
-- the payment in its place so the advance counts once.
-- ---------------------------------------------------------------------------
ALTER TABLE banksms.transactions ADD COLUMN linked_loan_id BIGINT UNIQUE;

-- ---------------------------------------------------------------------------
-- payees: the people and businesses money goes to, under every spelling the
-- banks use for them (masked, transliterated, truncated). Seeded from the
-- labeling round with `apex-rust import-payees`, never from this file: the
-- repository is public.
-- ---------------------------------------------------------------------------
CREATE TABLE banksms.payees (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  kind        TEXT NOT NULL CHECK (kind IN
                ('supplier', 'driver', 'employee', 'owner', 'family', 'bank', 'merchant', 'other')),
  category    TEXT,                   -- categories.key: what payments to them usually are
  consistency TEXT NOT NULL DEFAULT 'varies' CHECK (consistency IN ('always', 'varies')),
  driver_id   BIGINT REFERENCES public.drivers(id),
  employee_id BIGINT REFERENCES public.employees(id),
  notes       TEXT,
  created_by  TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT payee_single_party CHECK (driver_id IS NULL OR employee_id IS NULL)
);

CREATE TABLE banksms.payee_aliases (
  key        TEXT PRIMARY KEY,          -- the counterparty, folded (classify::fold)
  payee_id   BIGINT NOT NULL REFERENCES banksms.payees(id) ON DELETE CASCADE,
  spelling   TEXT NOT NULL,             -- as the bank wrote it
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX payee_aliases_payee_idx ON banksms.payee_aliases (payee_id);

-- ---------------------------------------------------------------------------
-- classifications: what the classifier concluded about a transaction and
-- what a person then did with it. One row per transaction.
--   applied   — at least 95% sure; written to the transaction.
--   suggested — not sure enough; waiting for review, the transaction's
--               category untouched (a person named by a label may already be
--               filled in).
--   accepted  — a person saved what was applied or suggested.
--   corrected — a person saved something else. The rule that produced it
--               loses its automatic say until it has earned it back.
--   dismissed — a person said no; never suggested again.
-- ---------------------------------------------------------------------------
CREATE TABLE banksms.classifications (
  transaction_id BIGINT PRIMARY KEY REFERENCES banksms.transactions(id) ON DELETE CASCADE,
  status         TEXT NOT NULL CHECK (status IN ('applied', 'suggested', 'accepted', 'corrected', 'dismissed')),
  rule           TEXT NOT NULL,
  confidence     NUMERIC(5,4) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  reason         TEXT NOT NULL,
  category       TEXT,
  driver_id      BIGINT,
  employee_id    BIGINT,
  linked_loan_id BIGINT,
  payee_id       BIGINT REFERENCES banksms.payees(id) ON DELETE SET NULL,
  pair_id        BIGINT,                -- the other side: internal-transfer partner, refunded original
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_by     TEXT,
  decided_at     TIMESTAMPTZ
);
CREATE INDEX classifications_suggested_idx ON banksms.classifications (transaction_id)
  WHERE status = 'suggested';
